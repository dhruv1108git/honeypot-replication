"""Client for the internal model gateway (OpenAI-compatible chat endpoint)."""

from __future__ import annotations

import json
import logging
import os
import random
import time
import urllib.error
import urllib.request
from dataclasses import dataclass

log = logging.getLogger(__name__)

# Gateway statuses worth retrying: timeouts, rate limits and overloaded replicas.
RETRYABLE_STATUS = frozenset({408, 429, 500, 502, 503, 504})


class TransientBackendError(RuntimeError):
    """A gateway failure that is likely to succeed on retry."""


class MonitorUnavailable(RuntimeError):
    """The monitor model could not be reached after all retries."""


@dataclass(frozen=True)
class MonitorRequest:
    model: str
    system: str
    user: str
    max_output_tokens: int
    temperature: float = 0.0


class GatewayBackend:
    """Sends monitor requests to the model gateway and returns the reply text."""

    def __init__(self, endpoint: str, timeout_s: float, token: str | None = None):
        self.endpoint = endpoint
        self.timeout_s = timeout_s
        self.token = token if token is not None else os.environ.get("COTMON_GATEWAY_TOKEN", "")

    def complete(self, req: MonitorRequest) -> str:
        body = {
            "model": req.model,
            "messages": [
                {"role": "system", "content": req.system},
                {"role": "user", "content": req.user},
            ],
            "max_tokens": req.max_output_tokens,
            "temperature": req.temperature,
        }
        http_req = urllib.request.Request(
            self.endpoint,
            data=json.dumps(body).encode("utf-8"),
            headers={
                "Content-Type": "application/json",
                "Authorization": f"Bearer {self.token}",
            },
            method="POST",
        )
        try:
            with urllib.request.urlopen(http_req, timeout=self.timeout_s) as resp:
                payload = json.load(resp)
        except urllib.error.HTTPError as exc:
            if exc.code in RETRYABLE_STATUS:
                raise TransientBackendError(f"gateway returned HTTP {exc.code}") from exc
            raise
        except (urllib.error.URLError, TimeoutError, ConnectionError) as exc:
            raise TransientBackendError(f"gateway request failed: {exc}") from exc
        return payload["choices"][0]["message"]["content"] or ""


class MonitorClient:
    """Wraps a backend with retries and exponential backoff."""

    def __init__(self, backend, max_retries: int = 4, backoff_s: float = 2.0, sleep=None):
        self.backend = backend
        self.max_retries = max_retries
        self.backoff_s = backoff_s
        self.sleep = sleep or time.sleep

    def complete(self, req: MonitorRequest) -> str:
        for attempt in range(self.max_retries + 1):
            try:
                return self.backend.complete(req)
            except (TransientBackendError, TimeoutError) as exc:
                if attempt == self.max_retries:
                    raise MonitorUnavailable(
                        f"monitor {req.model} unavailable after {attempt + 1} attempts"
                    ) from exc
                delay = self.backoff_s * 2**attempt * random.uniform(0.8, 1.2)
                log.warning("monitor request failed (%s); retry %d in %.1fs", exc, attempt + 1, delay)
                self.sleep(delay)
        raise AssertionError("unreachable")
